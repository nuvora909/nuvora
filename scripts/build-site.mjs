// Builds the public website from web/ into dist/: one index.html per clean URL, plus CSS, browser modules,
// media, the program cover art (covers/), a browser copy of the catalog, sitemap.xml, robots.txt and 404.html.
//
//   node scripts/build-site.mjs            (the dev server also runs this on start)
//   NUVORA_SITE_ORIGIN=https://example.org NUVORA_INDEXABLE=1 node scripts/build-site.mjs   (production)
//   node scripts/build-site.mjs --artifact --out dist-artifact   (relative-link preview for a Claude artifact)
import { mkdir, writeFile, readFile, readdir, stat, copyFile, rm } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const WEB = resolve(ROOT, 'web');
export const DIST = resolve(ROOT, 'dist');
const PAGES = ['home', 'programs-index', 'program', 'guide', 'brochure', 'careers', 'find', 'how', 'admissions', 'tuition', 'learn', 'about', 'contact', 'legal', 'notfound'];
const MEDIA = ['img', 'video', 'fonts'];

async function copyTree(from, to) {
  const entries = await readdir(from, { withFileTypes: true }).catch(() => []);
  await mkdir(to, { recursive: true });
  for (const e of entries) {
    const src = join(from, e.name), dst = join(to, e.name);
    if (e.isDirectory()) { await copyTree(src, dst); continue; }
    const [a, b] = await Promise.all([stat(src), stat(dst).catch(() => null)]);
    if (b && b.size === a.size && b.mtimeMs >= a.mtimeMs) continue; // unchanged media is not copied again
    await copyFile(src, dst);
  }
}

async function loadPages(today) {
  const out = [];
  for (const name of PAGES) {
    const file = resolve(WEB, 'pages', `${name}.mjs`);
    if (!(await stat(file).catch(() => null))) continue; // pages are added as they are written
    try {
      const mod = await import(pathToFileURL(file).href);
      out.push(...(await mod.default({ today })));
    } catch (e) {
      // NUVORA_BUILD_LENIENT=1 (used while several pages are being written at once) skips a broken page.
      if (process.env.NUVORA_BUILD_LENIENT !== '1') throw e;
      console.warn(`Skipped page module ${name}: ${e.message}`);
    }
  }
  return out;
}

function catalogModule(PROGRAMS, ROLES, TRACKS, extra) {
  const programs = PROGRAMS.map((p) => ({
    id: p.id, name: p.name, short: p.short, level: p.level, levelLabel: p.levelLabel, url: p.url, topics: p.topics,
    tagline: p.tagline, required: p.required, weeklyHours: p.weeklyHours, weeklyMin: p.weeklyMin, requiresCoding: p.requiresCoding,
    needsBachelor: p.needsBachelor, duration: p.duration, termCount: p.termCount, projects: p.projects, roles: p.roles,
    tuition: p.tuition, terms: p.terms.map((t) => ({ title: t.title, lessons: t.lessons, projects: t.projects })), credits: p.credits,
  }));
  const data = { programs, roles: ROLES, tracks: TRACKS, ...extra };
  return `// Generated by scripts/build-site.mjs from scripts/catalog.mjs and web/data. Do not edit.\nexport const CATALOG = ${JSON.stringify(data)};\n`;
}

// today: build "as of" a New York date (a Date at 00:00 UTC, as dates.mjs uses); unset, the build day. Production
// builds once a day (.github/workflows/daily-site.yml), so pages read without JavaScript stay current too.
export async function buildSite({ outDir = DIST, quiet = false, media = true, artifact = false, today } = {}) {
  const t0 = Date.now();
  const [{ PROGRAMS }, { ROLES, TRACKS, CAREER_NOTE }, site, { FAVICON }, { coverSvg, coverUrl, brochureCoverSvg, brochureCoverUrl }] = await Promise.all([
    import(pathToFileURL(resolve(WEB, 'data/programs.mjs')).href),
    import(pathToFileURL(resolve(WEB, 'data/careers.mjs')).href),
    import(pathToFileURL(resolve(WEB, 'data/site.mjs')).href),
    import(pathToFileURL(resolve(WEB, 'lib/icons.mjs')).href),
    import(pathToFileURL(resolve(WEB, 'lib/covers.mjs')).href),
  ]);

  // Fresh output, except media folders, which are synced incrementally.
  for (const entry of await readdir(outDir).catch(() => [])) {
    if (!MEDIA.includes(entry)) await rm(join(outDir, entry), { recursive: true, force: true });
  }
  await mkdir(outDir, { recursive: true });
  if (media) for (const m of MEDIA) await copyTree(resolve(WEB, 'static', m), join(outDir, m));
  await copyTree(resolve(WEB, 'assets/css'), join(outDir, 'css'));
  await copyTree(resolve(WEB, 'assets/js'), join(outDir, 'js'));
  await writeFile(join(outDir, 'favicon.svg'), FAVICON);
  // Program covers are drawn from code (web/lib/covers.mjs), so they are written on every build, media or not.
  await mkdir(join(outDir, 'covers'), { recursive: true });
  for (const p of PROGRAMS) {
    await writeFile(join(outDir, ...coverUrl(p).split('/').filter(Boolean)), coverSvg(p));
    await writeFile(join(outDir, ...brochureCoverUrl(p).split('/').filter(Boolean)), brochureCoverSvg(p));
  }
  await writeFile(join(outDir, 'js/catalog.mjs'), catalogModule(PROGRAMS, ROLES, TRACKS, {
    careerNote: CAREER_NOTE, faq: site.FAQ, schedule: site.SCHEDULE, consentVersion: site.SITE.consentVersion,
  }));

  const { setBuildDay } = await import(pathToFileURL(resolve(WEB, 'lib/layout.mjs')).href);
  setBuildDay(today);
  let pages;
  try { pages = await loadPages(today); } finally { setBuildDay(undefined); }
  const seen = new Set();
  for (const p of pages) {
    if (seen.has(p.path)) throw new Error(`Two pages claim ${p.path}`);
    seen.add(p.path);
    const file = p.path === '/404' ? join(outDir, '404.html') : join(outDir, ...p.path.split('/').filter(Boolean), 'index.html');
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, p.html);
  }

  const indexable = pages.filter((p) => p.path !== '/404' && !p.noindex).map((p) => p.path);
  await writeFile(join(outDir, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${indexable.map((p) => `  <url><loc>${site.SITE.origin}${p}</loc></url>`).join('\n')}\n</urlset>\n`);
  await writeFile(join(outDir, 'robots.txt'), `User-agent: *\nDisallow: /portal/\n\nSitemap: ${site.SITE.origin}/sitemap.xml\n`);
  if (artifact) await toArtifact(outDir, pages);
  if (!quiet) console.log(`Built ${pages.length} pages into ${outDir} in ${Date.now() - t0} ms${artifact ? ' (artifact preview)' : ''}`);
  return { pages: pages.map((p) => p.path), outDir };
}

// ---------------------------------------------------------------------------------------------------------------
// Artifact preview build: the same pages, made to work as a multi-file Claude artifact. Links become relative
// (directory URLs point at their index.html), the CSP meta is dropped because the artifact runtime adds its own
// scripts, and the student portal (which needs Nuvora's server) is replaced by a short note page.
const rootFor = (path) => '../'.repeat(path === '/404' ? 0 : path.split('/').filter(Boolean).length) || './';
function relLink(href, root) {
  const [, p0, rest] = /^([^?#]*)(.*)$/.exec(href);
  let p = p0 === '/portal' || p0.startsWith('/portal/') ? '/portal-preview/' : p0;
  if (p.endsWith('/')) p += 'index.html';
  return root + p.slice(1) + rest;
}
export function artifactHtml(html, path) {
  const root = rootFor(path);
  return html
    .replace(/<meta http-equiv="Content-Security-Policy"[^>]*>\n?/, '')
    .replace(/<script type="module" src="\/portal\/config\.js"><\/script>\n?/, '')
    .replace('<html lang="en">', `<html lang="en" data-root="${root}">`)
    .replace(/\b(href|src|action)="(\/(?!\/)[^"]*)"/g, (_, attr, v) => `${attr}="${relLink(v, root)}"`)
    .replace(/&quot;\/(img|video|fonts)\//g, `&quot;${root}$1/`);
}
async function toArtifact(outDir, pages) {
  const { page, pageHead } = await import(pathToFileURL(resolve(WEB, 'lib/layout.mjs')).href);
  const { html } = await import(pathToFileURL(resolve(WEB, 'lib/html.mjs')).href);
  const note = {
    path: '/portal-preview/',
    html: page({
      path: '/portal-preview/', title: 'Student portal', description: 'The Nuvora student portal runs on Nuvora’s own server with its database, so it is not part of this website preview.',
      body: html`${pageHead({ eyebrow: 'Student portal', title: 'The portal runs on Nuvora’s server', lede: 'Signing in, lessons, live classes and assignments need Nuvora’s database, so the student portal is not part of this website preview. It opens at /portal/ on the real site.' })}
        <section class="sec"><div class="wrap row"><a class="btn primary" href="/">Back to the website</a><a class="btn ghost" href="/how-it-works/">What the portal does</a></div></section>`,
    }),
  };
  for (const p of [...pages, note]) {
    const file = p.path === '/404' ? join(outDir, '404.html') : join(outDir, ...p.path.split('/').filter(Boolean), 'index.html');
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, artifactHtml(p.html, p.path));
  }
  for (const css of await readdir(join(outDir, 'css'))) {
    const f = join(outDir, 'css', css);
    await writeFile(f, (await readFile(f, 'utf8')).replace(/url\("\/(fonts|img)\//g, 'url("../$1/'));
  }
  await rm(join(outDir, 'sitemap.xml'), { force: true });
  await rm(join(outDir, 'robots.txt'), { force: true });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const out = argv.includes('--out') ? resolve(argv[argv.indexOf('--out') + 1]) : DIST;
  // --today YYYY-MM-DD: build as of that New York date (to preview or test a later day).
  const day = argv.includes('--today') ? argv[argv.indexOf('--today') + 1] : null;
  if (day && !/^\d{4}-\d{2}-\d{2}$/.test(day)) { console.error('--today takes a date: YYYY-MM-DD'); process.exit(1); }
  buildSite({ outDir: out, media: !argv.includes('--no-media'), quiet: argv.includes('--quiet'), artifact: argv.includes('--artifact'),
              today: day ? new Date(`${day}T00:00:00Z`) : undefined }).catch((e) => { console.error(e); process.exit(1); });
}
