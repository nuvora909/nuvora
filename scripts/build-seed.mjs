// Builds supabase/seed.sql from scripts/catalog.mjs: programs (with the tuition per term), their terms, one module of four lessons per
// term, the live-class pattern of every term and its three graded projects; plus the career roles and the
// skills each uses from the website's data (web/data), for the portal's goals and competency gaps.
import { writeFileSync } from 'node:fs';
import { PROGRAMS, TERMS, PROJECT_FOR_LESSON, LIVE_PATTERN, TIMEZONE, CAPACITY, TUITION } from './catalog.mjs';
import { ROLES } from '../web/data/careers.mjs';
import { PROGRAMS as WEB_PROGRAMS } from '../web/data/programs.mjs';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
// Deterministic lesson lengths between 18 and 36 minutes, so tests and demos are repeatable.
const duration = (code) => 1080 + ([...code].reduce((a, c) => (a * 31 + c.charCodeAt(0)) % 9973, 7) % 1081);
// Projects are shown as "Project 1: ...", unless the catalog already names their kind ("Capstone: ...").
const projectTitle = (title, i) => (/^[A-Z][a-z]+( project)?: /.test(title) ? title : `Project ${i + 1}: ${title}`);

// The list price of one term, by the program's level.
const tuition = (p) => {
  const usd = TUITION.perTerm[p.level];
  if (!(usd > 0)) throw new Error(`${p.id}: no tuition for level ${p.level}`);
  return usd.toFixed(2);
};

for (const p of PROGRAMS) {
  const codes = TERMS[p.id].flatMap((t) => t.lessons.map(([code]) => code));
  if (new Set(codes).size !== codes.length) throw new Error(`${p.id}: a lesson code appears in two terms`);
}

const out = ['-- Generated by scripts/build-seed.mjs from scripts/catalog.mjs. Do not edit by hand.', ''];

out.push('insert into public.programs (id, name, level, credits, duration_weeks, timezone, capacity, tuition_per_term_usd) values');
out.push(PROGRAMS.map((p) => `  (${q(p.id)}, ${q(p.name)}, ${q(p.level)}, ${p.credits}, ${LIVE_PATTERN.weeks}, ${q(TIMEZONE)}, ${CAPACITY}, ${tuition(p)})`).join(',\n') + ';', '');

out.push('insert into public.program_terms (program_id, term_no, title, badge) values');
out.push(PROGRAMS.flatMap((p) => TERMS[p.id].map((t, i) => `  (${q(p.id)}, ${i + 1}, ${q(t.title)}, ${q(t.badge)})`)).join(',\n') + ';', '');

// One module per term, in term order.
out.push('insert into public.modules (program_id, position, term_no, title) values');
out.push(PROGRAMS.flatMap((p) => TERMS[p.id].map((t, i) => `  (${q(p.id)}, ${i + 1}, ${i + 1}, ${q(t.title)})`)).join(',\n') + ';', '');

out.push('insert into public.lessons (module_id, position, code, title, kind, duration_seconds)');
out.push('select m.id, v.pos, v.code, v.title, \'video\', v.dur from public.modules m join (values');
out.push(PROGRAMS.flatMap((p) => TERMS[p.id].flatMap((t, ti) => t.lessons.map(([code, title], li) =>
  `  (${q(p.id)}, ${ti + 1}, ${li + 1}, ${q(code)}, ${q(title)}, ${duration(p.id + code)})`))).join(',\n'));
out.push(') as v(program_id, term_no, pos, code, title, dur) on m.program_id = v.program_id and m.term_no = v.term_no;', '');

// Every term runs the same weekly pattern; each lesson gets three weeks of live classes.
const L = LIVE_PATTERN;
const sessionRows = [];
for (const p of PROGRAMS) {
  TERMS[p.id].forEach((t, ti) => {
    for (let w = 1; w <= L.weeks; w++) {
      const lesson = t.lessons[Math.min(t.lessons.length - 1, Math.floor(((w - 1) * t.lessons.length) / L.weeks))][1];
      sessionRows.push(`  (${q(p.id)}, ${ti + 1}, ${w}, ${L.classDay}, ${q(L.classTime)}, ${L.classMinutes}, ${q(`Live class · Week ${w} · ${lesson}`)})`);
      sessionRows.push(`  (${q(p.id)}, ${ti + 1}, ${w}, ${L.officeDay}, ${q(L.officeTime)}, ${L.officeMinutes}, ${q(`Office hours · Week ${w}`)})`);
    }
  });
}
out.push('insert into public.session_templates (program_id, term_no, week, weekday, start_time, duration_minutes, title) values');
out.push(sessionRows.join(',\n') + ';', '');

const projectRows = PROGRAMS.flatMap((p) => TERMS[p.id].flatMap((t, ti) => t.projects.map(([title, days], i) =>
  `  (${q(p.id)}, ${ti + 1}, ${q(projectTitle(title, i))}, ${q('Submit a link to your work (GitHub, notebook or document). Graded on the four-level mastery rubric.')}, ${days})`)));
out.push('insert into public.assignment_templates (program_id, term_no, title, instructions, due_offset_days) values');
out.push(projectRows.join(',\n') + ';', '');

// Which project assesses each lesson (matched by its due day, which is unique within a term).
const assessed = PROGRAMS.flatMap((p) => TERMS[p.id].flatMap((t, ti) => t.lessons.map((_, li) =>
  `  (${q(p.id)}, ${ti + 1}, ${li + 1}, ${t.projects[PROJECT_FOR_LESSON[li]][1]})`)));
out.push('update public.lessons l set assessed_by = t.id');
out.push('from public.modules m, public.assignment_templates t, (values');
out.push(assessed.join(',\n'));
out.push(') as v(program_id, term_no, pos, due)');
out.push('where m.id = l.module_id and v.program_id = m.program_id and v.term_no = m.term_no and v.pos = l.position');
out.push('  and t.program_id = m.program_id and t.term_no = m.term_no and t.due_offset_days = v.due;', '');

// Career roles, the skills each uses (with the lesson that teaches it), and the roles each program prepares
// for, in the website's order (the first is the goal suggested to a student of that program).
const roleIds = Object.keys(ROLES);
const taught = new Set(PROGRAMS.flatMap((p) => TERMS[p.id].flatMap((t) => t.lessons.map(([code]) => code))));
for (const [id, r] of Object.entries(ROLES)) {
  for (const [, code] of r.skills) if (!taught.has(code)) throw new Error(`${id}: no program teaches ${code}`);
}
out.push('insert into public.career_roles (id, title, summary, position) values');
out.push(roleIds.map((id, i) => `  (${q(id)}, ${q(ROLES[id].title)}, ${q(ROLES[id].summary)}, ${i + 1})`).join(',\n') + ';', '');
out.push('insert into public.role_skills (role_id, position, skill, lesson_code) values');
out.push(roleIds.flatMap((id) => ROLES[id].skills.map(([skill, code], i) => `  (${q(id)}, ${i + 1}, ${q(skill)}, ${q(code)})`)).join(',\n') + ';', '');
out.push('insert into public.program_roles (program_id, role_id, position) values');
out.push(WEB_PROGRAMS.flatMap((p) => p.roles.map((role, i) => `  (${q(p.id)}, ${q(role)}, ${i + 1})`)).join(',\n') + ';', '');

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
const terms = PROGRAMS.reduce((n, p) => n + TERMS[p.id].length, 0);
console.log(`seed.sql written: ${PROGRAMS.length} programs, ${terms} terms, ${sessionRows.length} session templates, ${projectRows.length} projects`);
