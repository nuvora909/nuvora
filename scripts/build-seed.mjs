// Builds supabase/seed.sql from scripts/catalog.mjs.
import { writeFileSync } from 'node:fs';
import { PROGRAMS, LIVE_PATTERN, TIMEZONE, CAPACITY } from './catalog.mjs';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
// Deterministic lesson lengths between 18 and 36 minutes, so tests and demos are repeatable.
const duration = (code) => 1080 + ([...code].reduce((a, c) => (a * 31 + c.charCodeAt(0)) % 9973, 7) % 1081);

const out = ['-- Generated by scripts/build-seed.mjs from scripts/catalog.mjs. Do not edit by hand.', ''];

out.push('insert into public.programs (id, name, level, credits, duration_weeks, timezone, capacity) values');
out.push(PROGRAMS.map((p) => `  (${q(p.id)}, ${q(p.name)}, ${q(p.level)}, ${p.credits}, ${LIVE_PATTERN.weeks}, ${q(TIMEZONE)}, ${CAPACITY})`).join(',\n') + ';', '');

out.push('insert into public.modules (program_id, position, title) values');
out.push(PROGRAMS.flatMap((p) => p.modules.map(([title], i) => `  (${q(p.id)}, ${i + 1}, ${q(title)})`)).join(',\n') + ';', '');

out.push('insert into public.lessons (module_id, position, code, title, kind, duration_seconds)');
out.push('select m.id, v.pos, v.code, v.title, \'video\', v.dur from public.modules m join (values');
out.push(PROGRAMS.flatMap((p) => p.modules.flatMap(([, lessons], mi) => lessons.map(([code, title], li) =>
  `  (${q(p.id)}, ${mi + 1}, ${li + 1}, ${q(code)}, ${q(title)}, ${duration(p.id + code)})`))).join(',\n'));
out.push(') as v(program_id, mpos, pos, code, title, dur) on m.program_id = v.program_id and m.position = v.mpos;', '');

const L = LIVE_PATTERN;
const sessionRows = [];
for (const p of PROGRAMS) {
  for (let w = 1; w <= L.weeks; w++) {
    const mod = p.modules[(w - 1) % p.modules.length][0];
    sessionRows.push(`  (${q(p.id)}, ${w}, ${L.classDay}, ${q(L.classTime)}, ${L.classMinutes}, ${q(`Live class · Week ${w} · ${mod}`)})`);
    sessionRows.push(`  (${q(p.id)}, ${w}, ${L.officeDay}, ${q(L.officeTime)}, ${L.officeMinutes}, ${q(`Office hours · Week ${w}`)})`);
  }
}
out.push('insert into public.session_templates (program_id, week, weekday, start_time, duration_minutes, title) values');
out.push(sessionRows.join(',\n') + ';', '');

out.push('insert into public.assignment_templates (program_id, title, instructions, due_offset_days) values');
out.push(PROGRAMS.flatMap((p) => p.assignments.map(([title, days]) =>
  `  (${q(p.id)}, ${q(title)}, ${q('Submit a link to your work (GitHub, notebook or document). Graded on the four-level mastery rubric.')}, ${days})`)).join(',\n') + ';', '');

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log(`seed.sql written: ${PROGRAMS.length} programs, ${sessionRows.length} session templates`);
